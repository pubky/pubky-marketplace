/**
 * Copyright request field length limits, in characters (after trimming).
 */

/** Names, postal address parts, phone number and signature. */
export const COPYRIGHT_SHORT_FIELD_MAX_LENGTH = 200;

/** Longest email address allowed by RFC 5321. */
export const COPYRIGHT_EMAIL_MAX_LENGTH = 254;

/** A single URL, such as the infringing content URL. */
export const COPYRIGHT_URL_MAX_LENGTH = 2048;

/** The free-text list of original content URLs. */
export const COPYRIGHT_ORIGINAL_CONTENT_URLS_MAX_LENGTH = 4000;

/** The brief description of the original content. */
export const COPYRIGHT_BRIEF_DESCRIPTION_MAX_LENGTH = 5000;
